/**
 * useAuctionSocket.ts
 * The client half of the server-owned auction.
 *
 * This hook holds no auction logic, and that is the entire point. It sends
 * intents and renders whatever the room sends back. Nothing here decides
 * whether a bid is legal, what the next ask is, or who is winning — every one
 * of those questions is answered by `auction/room.py`, because a client that
 * computes them is a client that can disagree with the room, and ten clients
 * disagreeing with the room is the bug this whole phase exists to prevent.
 *
 * Compare `useAuctionEngine`, which owns the auction outright. That is still
 * the right design for `/console`: one operator, one browser, no server. This
 * is the right design for a room. They coexist deliberately.
 *
 * Three things this hook does take responsibility for:
 *
 *   **Reconnection.** Auctions run for hours and laptops sleep. The socket
 *   reconnects with backoff and re-claims its seat automatically, because
 *   losing your franchise to a dropped Wi-Fi signal mid-lot is not acceptable.
 *
 *   **Staleness.** Every bid carries the `lot_version` the user could actually
 *   see when they clicked. If the room has moved on, the room refuses it. That
 *   is what stops a click landing on a lot that changed while the packet was in
 *   flight — see the race guard in `room.py`.
 *
 *   **StrictMode.** The socket is created inside the effect rather than in a
 *   memo. React 18 mounts, unmounts and remounts in development; a memoised
 *   socket would be closed by the first cleanup and the second mount would
 *   reuse the dead instance. This mistake has been made in this codebase
 *   before, in the Phase 3 mock feed.
 */
import { useCallback, useEffect, useMemo, useRef, useState } from "react";

import { wsUrl } from "../console/apiBase";
import { useAccount } from "../console/accountStore";
import { useRoom, withRoom } from "../console/auctionRoom";

/* ------------------------------------------------------------------ *
 * The wire format, mirroring auction/schemas.py
 * ------------------------------------------------------------------ */

export type Phase = "lobby" | "waiting" | "live" | "finished";
export type Role = "auctioneer" | "franchise" | "spectator";

export interface Seat {
  role: Role;
  team_id: number | null;
  team_code: string | null;
  client_id: string;
}

export interface TeamState {
  id: number;
  name: string;
  code: string;
  color: string;
  spent: number;
  left: number;
  size: number;
  /** [playerId, price] pairs for everything this franchise has bought. */
  buys?: [number, number][];
  overseas: number;
  max_bid: number;
  connected: boolean;
  /** Strategic buffers this franchise has not spent yet. */
  timeouts_left: number;
  uncapped?: number;
  /** Still owed to reach the room's minimums; places the room keeps back. */
  overseas_needed?: number;
  uncapped_needed?: number;
  /** Has this franchise acknowledged the current rules_version? */
  acknowledged?: boolean;
}

/** One guideline in the pre-auction briefing, generated by the room from its rules. */
export interface BriefingItem {
  id: string;
  title: string;
  body: string;
}

export interface LotState {
  player_id: number;
  player_name: string;
  role: string;
  country: string | null;
  overseas: boolean;
  rating: number | null;
  base: number;
  bid: number;
  bidder_id: number | null;
  bidder_code: string | null;
  next_ask: number;
  version: number;

  /**
   * Which countdown is running, and therefore what its expiry means:
   * `opening` (7s, no bid) -> UNSOLD; `closing` (7s, a bid stands) -> SOLD;
   * `timeout` (the 30s decision buffer) -> the last recorded bid: SOLD if one
   * stands, UNSOLD if none does.
   */
  /** "presenting": a marquee player's reveal is playing; bidding opens after it. */
  clock: "presenting" | "opening" | "closing" | "timeout" | null;
  /** Unix seconds the countdown fires. */
  deadline: number | null;
  /**
   * Seconds left when the room wrote this frame.
   *
   * This, not `deadline`, is what a display should count down from. Seven
   * seconds is short enough that a laptop whose clock runs two seconds fast
   * would otherwise show a lot expiring while the room still holds it open.
   */
  ends_in: number | null;
  /** Full length of a marquee hold while `clock` is "presenting"; else null. */
  reveal_seconds?: number | null;
  timeout_by_id: number | null;
  timeout_by_code: string | null;
  /** Franchises that have bid on this lot and not withdrawn from it. */
  contenders: number[];
  contender_codes: string[];
  /** Franchises that folded on this lot. They may not bid on it again. */
  folded?: number[];
  folded_codes?: string[];
  has_bid?: boolean;
  /** The +5 / +10 / +15 Cr jump bids as absolute prices, computed by the room. */
  jump_options?: number[];
  /** team id -> why it cannot meet the next ask, or null when it can. */
  blocked?: Record<string, string | null>;
}

/**
 * A countdown, packaged so a display can tick it locally.
 *
 * `key` changes on every re-arm. A component keyed on it restarts its own
 * animation from the top rather than interpolating from wherever the last
 * buffer had got to, which is what makes a bid visibly reset the clock.
 */
export interface LotClock {
  kind: "opening" | "closing" | "timeout";
  /** Seconds remaining as of the frame this came from. */
  endsIn: number;
  /** The full length of this kind of buffer, for a progress bar's denominator. */
  total: number;
  key: string;
}

export type RoomMode = "online" | "offline";
export type AuctioneerKind = "manual" | "ai";

/** A sale, as the SOLD banner announces it (room.last_sale). */
export interface LastSale {
  seq: number;
  player_id: number;
  player: string;
  team_id: number;
  team: string;
  team_code: string;
  /** Lakh. */
  price: number;
  /** The player's base price, lakh. */
  base?: number;
}

export interface LogItem {
  seq: number;
  kind: "note" | "bid" | "sold" | "unsold" | "timeout" | "withdraw";
  what: string;
  amount: number | null;
  ts: number;
}

export interface RoomState {
  version: number;
  phase: Phase;
  /**
   * Message types this server build accepts.
   *
   * Optional because a server older than this field simply will not send it —
   * which is itself the answer: absent means "old enough to predate the
   * capability list", and every check below treats that as unsupported.
   *
   * It exists because the two halves of this app reach the user by different
   * routes. `dist/` is re-read from disk on every request, so a rebuilt
   * frontend arrives on a refresh; Python is loaded once at process start, so a
   * backend change arrives only on a restart. A browser running today's bundle
   * against yesterday's uvicorn sends messages that server has never heard of,
   * and the only symptom is a control that appears to do nothing.
   */
  supports?: string[];
  /** The room's code and kind. Absent from a server that predates rooms. */
  room?: string;
  room_kind?: "mega" | "mini";
  /** Who runs it: an Auctioneer account, or a Delegate account. */
  room_type?: "auctioneer" | "delegate";
  rules: {
    /** Total Budget, lakh. */
    purse: number;
    /** Total Squad: the most players a franchise may hold. */
    max_squad: number;
    /** Minimum Players a franchise must finish with. */
    min_squad: number;
    /** Maximum Players to go under the hammer in this auction. */
    max_players?: number;
    max_overseas: number;
    min_overseas?: number;
    min_uncapped?: number;
    /** Standard step, lakh (25 = 0.25 Cr), and the jump-bid shortcuts. */
    increment?: number;
    jump_steps?: number[];
    max_teams?: number;
    /** The clock, owned by the room so the dial cannot disagree with it. */
    open_seconds: number;
    close_seconds: number;
    timeout_seconds: number;
    timeouts_per_team: number;
    /**
     * How the room runs. Online: bids on screen, on the clock. Offline:
     * placards in the room, no clock, the auctioneer logs each sale. Absent
     * from a server older than hybrid mode, which is online.
     */
    mode?: RoomMode;
    /** Who holds the chair in an online room. */
    auctioneer?: AuctioneerKind;
  };
  /**
   * Bumped on every setup change. A franchise must acknowledge exactly this
   * number before the room accepts a bid, fold or buffer from it.
   */
  rules_version?: number;
  /** The briefing, generated by the room from `rules`. */
  briefing?: BriefingItem[];
  teams: TeamState[];
  lot: LotState | null;
  log: LogItem[];
  counts: { available: number; sold: number; unsold: number; spent: number };
  unsold?: number[];
  countdown_ends_at: number | null;
  /** The latest sale, for the SOLD banner. A new `seq` is a new sale. */
  last_sale?: LastSale | null;
  /**
   * How players reach the block: "random" (online -- the room draws each one
   * itself) or "manual" (offline -- the auctioneer puts them up).
   */
  draw?: "random" | "manual";
  /** Unix time the next random draw is due, between lots. */
  next_draw_at?: number | null;
  connected: number;
  /**
   * Whether the auctioneer's chair is occupied. Optional so an older frame that
   * predates the field reads as "unknown" (falsy) rather than throwing; the seat
   * picker treats it as "the chair is taken, show it as such".
   */
  auctioneer_present?: boolean;
}

export type SocketStatus = "connecting" | "open" | "reconnecting" | "closed";

/** What we asked to be, so a reconnect can ask for it again. */
export interface SeatRequest {
  role: "auctioneer" | "franchise";
  teamId?: number;
  displayName?: string;
  /**
   * The auctioneer password. Sent only for an auctioneer claim and held here so
   * a reconnect can re-claim the chair without prompting again. Never rendered,
   * only forwarded to the room, which verifies it server-side.
   */
  password?: string;
}

/* ------------------------------------------------------------------ *
 * Endpoint
 * ------------------------------------------------------------------ */

/**
 * The room's address, resolved by `apiBase` rather than worked out here.
 *
 * This function used to carry its own copy of the dev/production split, which
 * meant the socket could disagree with `ragClient` about where the backend is.
 * That disagreement had a specific and confusing symptom: the console would
 * hydrate its 284-player roster over REST perfectly well and then fail to join
 * the room, because the two halves were dialling different places.
 *
 * `wsUrl` derives ws/wss and the authority from the same base the REST client
 * uses, so the two can no longer drift. VITE_AUCTION_WS still overrides it
 * outright for the case where the socket really does live somewhere else.
 */
function socketUrl(): string {
  // The room code from the page's address (console/auctionRoom.ts); none
  // means the default room.
  return withRoom(wsUrl());
}

/** Backoff schedule, in ms. Caps rather than growing without bound. */
const BACKOFF = [400, 900, 1800, 3000, 5000, 8000];
/** Close codes for a room code the server will not serve: no retry. */
const ROOM_REFUSALS = new Set([4400, 4403, 4404, 4429]);
const PING_INTERVAL = 25_000;

export interface AuctionSocket {
  status: SocketStatus;
  state: RoomState | null;
  seat: Seat | null;
  /** Most recent refusal from the room. Cleared by `dismissError`. */
  error: string | null;
  dismissError: () => void;
  /**
   * Why the server turned this page's room code away (no such room, not a
   * code, every room in use). Set once and kept: the socket does not retry.
   */
  roomError: string | null;

  /** Seconds left on the waiting-room countdown, or null outside `waiting`. */
  secondsLeft: number | null;

  claimSeat: (request: SeatRequest) => void;
  /**
   * The seat to claim as soon as the socket (re)opens, without sending now.
   * For moving rooms: the next room's connection is not open yet when the
   * auctioneer submits their login, so the claim waits for it. Null forgets
   * any seat held in the room being left.
   */
  queueSeat: (request: SeatRequest | null) => void;
  openWaitingRoom: (seconds?: number) => void;
  startAuction: () => void;
  putUp: (playerId: number) => void;
  /** `amount` omitted bids the standard increment; supplied, it is a jumpbid. */
  bid: (amount?: number) => void;
  sell: () => void;
  markUnsold: () => void;
  undo: () => void;
  finish: () => void;
  /** Auctioneer: wipe the auction back to an empty lobby, keeping seats. */
  resetRoom: () => void;
  /**
   * Auctioneer: change purse and squad limits from the Auction Setup panel.
   *
   * Figures in the room's own units — purse in lakh, the rest as counts. The
   * room refuses anything that would make an existing squad illegal, and the
   * refusal arrives as an `error` frame like every other one.
   */
  setRules: (rules: SetupRules) => void;
  /**
   * Franchise: "I have read the briefing."
   *
   * Quotes the rules_version on screen. If the host changed the rules while
   * this franchise was reading, the room refuses it and the newer briefing is
   * already what is rendered, so the franchise simply reads again.
   */
  acknowledgeRules: () => void;
  /**
   * Franchise: step out of the contest for the lot on the block.
   *
   * An accelerator, not a veto. The buffer settles every lot on its own; this
   * says "do not wait for me", and once everyone but the standing bidder has
   * said it the lot goes at once instead of sitting out a buffer nobody will
   * use. Per-lot: the next player puts you back in contention.
   */
  withdraw: () => void;
  /** Franchise: call the 30-second decision buffer (pauses the 7s timer). */
  callTimeout: () => void;
  /** Auctioneer, before the start: online or offline, manual or AI. */
  setMode: (mode: RoomMode, auctioneer?: AuctioneerKind) => void;
  /** Auctioneer, offline: the room sold the lot by placard to `teamId` for `price` lakh. */
  recordSale: (teamId: number, price: number) => void;
  /** The room is offline: no bid controls, no clock. */
  offline: boolean;

  /** Convenience readings derived from `state` and `seat`. */
  myTeam: TeamState | null;
  isWinning: boolean;
  canAct: boolean;

  /** The running countdown, or null when nothing is armed. */
  lotClock: LotClock | null;
  /** Lifelines this franchise has left. */
  timeoutsLeft: number;
  /** This franchise has bid on the current lot and not withdrawn. */
  amContending: boolean;
  /**
   * Whether these two controls should be offered at all.
   *
   * Mirrors the room's own refusals so a control that would be rejected is
   * never presented as available. The room re-checks regardless and its answer
   * is the one that counts -- this only avoids offering a dead button.
   */
  canWithdraw: boolean;
  canCallTimeout: boolean;
  /** This franchise has acknowledged the current rules (rule 7). */
  briefed: boolean;
  /** This franchise folded on the lot currently on the block (rule 6). */
  hasFolded: boolean;
  /** The room's own reason this franchise cannot meet the next ask, if any. */
  myBlockedReason: string | null;
  /** True when this tab acknowledged an older rules_version than the current one. */
  rulesChanged: boolean;
}

/** The host-editable Auction Setup, in the room's units (purse in lakh). */
export interface SetupRules {
  purse: number;
  maxSquad: number;
  minSquad: number;
  maxOverseas: number;
  maxPlayers?: number;
  minOverseas?: number;
}

export function useAuctionSocket(): AuctionSocket {
  const [status, setStatus] = useState<SocketStatus>("connecting");
  const [state, setState] = useState<RoomState | null>(null);
  const [seat, setSeat] = useState<Seat | null>(null);
  const [error, setError] = useState<string | null>(null);
  const [roomError, setRoomError] = useState<string | null>(null);
  const [now, setNow] = useState(() => Date.now());

  const socketRef = useRef<WebSocket | null>(null);
  /** Held across reconnects so the seat can be re-claimed without asking. */
  const seatRequest = useRef<SeatRequest | null>(null);
  /** Read inside send() so a bid always quotes the version on screen. */
  const lotVersion = useRef<number | null>(null);
  const attempt = useRef(0);
  // The room this tab is in (console/auctionRoom.ts). The connection below is
  // to that room, and moves when it does.
  const room = useRoom();
  // Whose account this tab is signed in as. The server reads it from the
  // session cookie when the socket opens, so a different account means a new
  // connection; while the first check is in flight there is nothing to send.
  const signedIn = useAccount();
  const accountKey = signedIn.status === "loading" ? "loading" : String(signedIn.account?.id ?? "none");

  /* ---------------- the connection ---------------- */

  useEffect(() => {
    // Per room. A local flag rather than a ref: when the room changes, the old
    // socket's close and its last frames arrive after this effect has already
    // run again for the new room, and must be ignored rather than mistaken
    // for the new room's.
    let stopped = false;
    let reconnectTimer: number | undefined;
    let pingTimer: number | undefined;

    setState(null);
    setSeat(null);
    setRoomError(null);
    attempt.current = 0;
    lotVersion.current = null;

    // At the Live Bidding entry, before a room is created or joined, there is
    // nothing to connect to.
    if (!room.chosen) {
      setStatus("closed");
      return;
    }
    if (accountKey === "loading") {
      setStatus("connecting");
      return;
    }

    const connect = () => {
      if (stopped) return;

      // Created here, not memoised — StrictMode's double mount would otherwise
      // hand the second mount a socket the first mount's cleanup had closed.
      const socket = new WebSocket(socketUrl());
      socketRef.current = socket;
      setStatus(attempt.current === 0 ? "connecting" : "reconnecting");

      socket.onopen = () => {
        attempt.current = 0;
        setStatus("open");

        // Re-claim the seat we held before the drop. The room frees a seat on
        // disconnect, so this is a fresh claim and can legitimately fail if
        // someone else took it meanwhile — which surfaces as an error, not as
        // a silent demotion to spectator.
        const request = seatRequest.current;
        if (request) {
          socket.send(
            JSON.stringify({
              type: "join",
              role: request.role,
              team_id: request.teamId ?? null,
              display_name: request.displayName ?? null,
              password: request.password ?? null,
            }),
          );
        }

        pingTimer = window.setInterval(() => {
          if (socket.readyState === WebSocket.OPEN) {
            socket.send(JSON.stringify({ type: "ping" }));
          }
        }, PING_INTERVAL);
      };

      socket.onmessage = (event) => {
        if (stopped) return; // a frame from the room this tab has left
        let payload: Record<string, unknown>;
        try {
          payload = JSON.parse(event.data as string);
        } catch {
          return; // The server does not emit malformed JSON; ignore noise.
        }

        switch (payload.type) {
          case "state": {
            const next = payload as unknown as RoomState;
            setState(next);
            lotVersion.current = next.lot?.version ?? null;
            break;
          }
          case "joined":
            setSeat((payload as { seat: Seat }).seat);
            break;
          case "error":
            if (payload.about === "room") setRoomError(String(payload.message ?? "That room is not available."));
            else setError(String(payload.message ?? "The room refused that."));
            break;
          case "pong":
          default:
            break;
        }
      };

      socket.onclose = (event) => {
        window.clearInterval(pingTimer);
        // 44xx: the server turned the room code away (auction/ws.py `_refuse`).
        // Retrying would be refused the same way, so stop and say why.
        if (stopped) return; // the room this tab has left
        if (ROOM_REFUSALS.has(event.code)) {
          setStatus("closed");
          return;
        }
        setStatus("reconnecting");
        const wait = BACKOFF[Math.min(attempt.current, BACKOFF.length - 1)];
        attempt.current += 1;
        reconnectTimer = window.setTimeout(connect, wait);
      };

      // `onerror` is always followed by `onclose`, which owns the retry. Doing
      // anything here as well would schedule two reconnects for one failure.
      socket.onerror = () => {};
    };

    connect();

    return () => {
      stopped = true;
      window.clearTimeout(reconnectTimer);
      window.clearInterval(pingTimer);
      socketRef.current?.close();
      socketRef.current = null;
    };
    // The room itself (entering one, leaving for the entry, moving between
    // codes) and the account. Not `creating` clearing once the chair is taken
    // -- same room, same account.
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [room.chosen, room.code, accountKey]);

  /* ---------------- countdown ---------------- */

  useEffect(() => {
    if (state?.phase !== "waiting" || !state.countdown_ends_at) return;
    const timer = window.setInterval(() => setNow(Date.now()), 1000);
    return () => window.clearInterval(timer);
  }, [state?.phase, state?.countdown_ends_at]);

  const secondsLeft = useMemo(() => {
    if (state?.phase !== "waiting" || !state.countdown_ends_at) return null;
    // `ceil`, not `round`: a countdown should show "1" for the whole of the
    // last second and reach zero only when the time is actually up.
    const msLeft = state.countdown_ends_at * 1000 - now;
    return Math.max(0, Math.ceil(msLeft / 1000));
  }, [state?.phase, state?.countdown_ends_at, now]);

  /* ---------------- sending ---------------- */

  const send = useCallback((payload: Record<string, unknown>) => {
    const socket = socketRef.current;
    if (!socket || socket.readyState !== WebSocket.OPEN) {
      setError("Not connected to the auction room.");
      return;
    }
    socket.send(JSON.stringify(payload));
  }, []);

  const claimSeat = useCallback(
    (request: SeatRequest) => {
      seatRequest.current = request;
      send({
        type: "join",
        role: request.role,
        team_id: request.teamId ?? null,
        display_name: request.displayName ?? null,
        password: request.password ?? null,
      });
    },
    [send],
  );

  // Read through a ref so the callback quotes the version on screen at the
  // moment of the click, not the one captured when it was created.
  const rulesVersion = useRef<number>(0);
  useEffect(() => {
    rulesVersion.current = state?.rules_version ?? 0;
  }, [state?.rules_version]);
  // The last version this tab acknowledged, so a briefing that reappears can
  // say the rules changed rather than looking like a glitch.
  const [ackedVersion, setAckedVersion] = useState<number | null>(null);
  const acknowledgeRules = useCallback(() => {
    setAckedVersion(rulesVersion.current);
    send({ type: "acknowledge_rules", rules_version: rulesVersion.current });
  }, [send]);

  const bid = useCallback(
    (amount?: number) => {
      // The version is attached here rather than by the caller, so no call site
      // can forget it and quietly reintroduce the race.
      send({
        type: "bid",
        amount: amount ?? null,
        lot_version: lotVersion.current,
      });
    },
    [send],
  );

  const actions = useMemo(
    () => ({
      openWaitingRoom: (seconds = 600) =>
        send({ type: "open_waiting_room", countdown_seconds: seconds }),
      startAuction: () => send({ type: "start_auction" }),
      putUp: (playerId: number) => send({ type: "put_up", player_id: playerId }),
      sell: () => send({ type: "sell" }),
      markUnsold: () => send({ type: "unsold" }),
      undo: () => send({ type: "undo" }),
      finish: () => send({ type: "finish" }),
      resetRoom: () => send({ type: "reset" }),
      setRules: (rules: SetupRules) =>
        send({
          type: "set_rules",
          // snake_case on the wire: the schema is the server's and the server
          // does not bend its naming to the client's.
          purse: rules.purse,
          max_squad: rules.maxSquad,
          min_squad: rules.minSquad,
          max_overseas: rules.maxOverseas,
          max_players: rules.maxPlayers ?? null,
          min_overseas: rules.minOverseas ?? null,
        }),
      withdraw: () => send({ type: "withdraw" }),
      callTimeout: () => send({ type: "timeout" }),
      setMode: (mode: RoomMode, auctioneer: AuctioneerKind = "manual") =>
        send({ type: "set_mode", mode, auctioneer }),
      recordSale: (teamId: number, price: number) =>
        send({ type: "record_sale", team_id: teamId, price }),
    }),
    [send],
  );

  /* ---------------- derived ---------------- */

  const myTeam = useMemo(
    () =>
      state && seat?.team_id != null
        ? (state.teams.find((team) => team.id === seat.team_id) ?? null)
        : null,
    [state, seat?.team_id],
  );

  const isWinning = !!(
    state?.lot &&
    seat?.team_id != null &&
    state.lot.bidder_id === seat.team_id
  );

  /* ---------------- the clock ----------------
     Packaged, not ticked. Counting down here would re-render every consumer of
     this hook ten times a second during the tensest part of a lot; the display
     component owns its own tick and this only tells it where to start. */

  const lotClock = useMemo<LotClock | null>(() => {
    const lot = state?.lot;
    if (!lot?.clock || lot.ends_in == null || !state) return null;
    // No dial while a marquee reveal plays: the bidding clock has not started,
    // and the reveal covers the block anyway.
    if (lot.clock === "presenting") return null;
    const total =
      lot.clock === "opening"
        ? state.rules.open_seconds
        : lot.clock === "timeout"
          ? state.rules.timeout_seconds
          : state.rules.close_seconds;
    return {
      kind: lot.clock,
      endsIn: lot.ends_in,
      total: total || 7,
      // Deadline is in the key, so re-arming the same kind of buffer still
      // reads as a new clock and restarts the dial.
      key: `${lot.player_id}:${lot.clock}:${lot.deadline}`,
    };
  }, [state]);

  const myTeamId = seat?.team_id ?? null;
  const timeoutsLeft = myTeam?.timeouts_left ?? 0;
  const live = state?.phase === "live";
  const connected = status === "open" && seat !== null;

  const amContending = !!(
    state?.lot &&
    myTeamId != null &&
    (state.lot.contenders ?? []).includes(myTeamId)
  );

  // Rule 7: nothing is offered to a franchise that has not read these rules.
  const briefed = !!myTeam?.acknowledged;
  // Rule 6: a franchise that folded is out of this lot until the next one.
  const hasFolded = !!(
    state?.lot && myTeamId != null && (state.lot.folded ?? []).includes(myTeamId)
  );
  const leading = state?.lot?.bidder_id === myTeamId;

  // Any franchise may fold, whether or not it has bid -- except the leader,
  // for whom stepping back would be retracting a standing offer.
  const canWithdraw = !!(
    connected &&
    live &&
    state?.lot &&
    state.lot.clock !== "presenting" &&
    briefed &&
    !leading &&
    !hasFolded
  );

  // Rule 5: decision time is available whenever a player is up, before or
  // after the first bid, but not to the leader, a folded team, or on top of a
  // buffer already running.
  const canCallTimeout = !!(
    connected &&
    live &&
    briefed &&
    (state?.lot?.clock === "opening" || state?.lot?.clock === "closing") &&
    !leading &&
    !hasFolded &&
    timeoutsLeft > 0
  );

  const myBlockedReason =
    state?.lot && myTeamId != null ? (state.lot.blocked?.[String(myTeamId)] ?? null) : null;

  return {
    status,
    state,
    seat,
    error,
    dismissError: useCallback(() => setError(null), []),
    roomError,
    secondsLeft,
    claimSeat,
    queueSeat: useCallback((request: SeatRequest | null) => {
      seatRequest.current = request;
    }, []),
    bid,
    ...actions,
    myTeam,
    isWinning,
    canAct: connected,
    lotClock,
    timeoutsLeft,
    amContending,
    canWithdraw,
    canCallTimeout,
    acknowledgeRules,
    briefed,
    hasFolded,
    myBlockedReason,
    offline: state?.rules.mode === "offline",
    rulesChanged:
      ackedVersion !== null && !briefed && ackedVersion !== (state?.rules_version ?? ackedVersion),
  };
}
